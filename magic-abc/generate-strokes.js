// Convertir a formato LETTER_PATHS (cada letra = un array continuo de {x,y})
const letterPaths = {};
for (const [char, strokeList] of Object.entries(strokes)) {
  const allPoints = [];
  for (let i = 0; i < strokeList.length; i++) {
    const stroke = strokeList[i];
    allPoints.push(...stroke.map(p => ({x: p.x, y: p.y})));
    // Pequeño conector entre trazos (casi invisible)
    if (i < strokeList.length - 1) {
      const last = stroke[stroke.length - 1];
      const next = strokeList[i + 1][0];
      allPoints.push({x: last.x, y: last.y}); // punto en el mismo lugar (conector invisible)
    }
  }
  letterPaths[char] = allPoints;
}

const js = 'const LETTER_PATHS = ' + JSON.stringify(letterPaths) + ';';
fs.writeFileSync(path.join(__dirname, 'letter-paths.js'), js);

let totalPts = 0;
for (const [k, v] of Object.entries(letterPaths)) totalPts += v.length;
console.log(`✅ ${Object.keys(letterPaths).length} letras generadas con TRAZOS DE ESCRITURA`);
console.log(`   Total puntos: ${totalPts} (promedio ${Math.round(totalPts/Object.keys(letterPaths).length)} por letra)`);
